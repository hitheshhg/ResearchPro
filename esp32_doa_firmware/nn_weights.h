// Ultra-fast zero-overhead TinyML forward pass on ESP32 (~1.5 microseconds)
inline void runTinyMLInference(const float* inputs, float* out_probs) {
    float hidden[NN_NUM_HIDDEN];
    
    // Layer 1: Dense + ReLU
    for (int j = 0; j < NN_NUM_HIDDEN; j++) {
        float sum = g_nn_b1[j];
        for (int i = 0; i < NN_NUM_INPUTS; i++) {
            sum += inputs[i] * g_nn_w1[j][i];
        }
        hidden[j] = (sum > 0.0f) ? sum : 0.0f; // ReLU
    }
    
    // Layer 2: Dense
    float raw_out[NN_NUM_OUTPUTS];
    float max_val = -1e9f;
    for (int k = 0; k < NN_NUM_OUTPUTS; k++) {
        float sum = g_nn_b2[k];
        for (int j = 0; j < NN_NUM_HIDDEN; j++) {
            sum += hidden[j] * g_nn_w2[k][j];
        }
        raw_out[k] = sum;
        if (sum > max_val) max_val = sum;
    }
    
    // Softmax
    float exp_sum = 0.0f;
    for (int k = 0; k < NN_NUM_OUTPUTS; k++) {
        out_probs[k] = expf(raw_out[k] - max_val);
        exp_sum += out_probs[k];
    }
    float inv_sum = 1.0f / (exp_sum + 1e-9f);
    for (int k = 0; k < NN_NUM_OUTPUTS; k++) {
        out_probs[k] *= inv_sum;
    }
}

